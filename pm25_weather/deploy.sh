#!/usr/bin/env bash
set -Eeuo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
[[ -f .env ]] && { set -a; source .env; set +a; }
AWS_REGION=${AWS_REGION:-us-east-1}; S3_BUCKET=${S3_BUCKET:-pm25-weather}; GLUE_DATABASE=${GLUE_DATABASE:-pm25_weather}; ICEBERG_TABLE=${ICEBERG_TABLE:-pm25_weather_iceberg}; IAM_ROLE=${IAM_ROLE:-LabRole}; GLUE_JOB=${GLUE_JOB:-pm25-iceberg-full-year-publish}; TRIGGER=${TRIGGER:-both}; STATE_MACHINE_NAME=${STATE_MACHINE_NAME:-pm25-weather-pipeline}; LAMBDA_RUNTIME=${LAMBDA_RUNTIME:-python3.13}
export AWS_DEFAULT_REGION="$AWS_REGION"
export TRIGGER
for cmd in aws python3; do command -v "$cmd" >/dev/null || { echo "Missing $cmd" >&2; exit 1; }; done
[[ "$TRIGGER" == manual || "$TRIGGER" == both || "$TRIGGER" == s3-event ]] || { echo 'TRIGGER must be manual, both or s3-event' >&2; exit 1; }
ACCOUNT=$(aws sts get-caller-identity --query Account --output text)
ROLE_ARN=$(aws iam get-role --role-name "$IAM_ROLE" --query Role.Arn --output text)
python3 - "$IAM_ROLE" <<'PY'
import json,subprocess,sys
role=json.loads(subprocess.check_output(['aws','iam','get-role','--role-name',sys.argv[1],'--output','json']))['Role']
principals=role['AssumeRolePolicyDocument'].get('Statement',[])
services=set()
for statement in principals:
    if statement.get('Effect')=='Allow':
        s=statement.get('Principal',{}).get('Service',[])
        services.update([s] if isinstance(s,str) else s)
missing={'lambda.amazonaws.com','glue.amazonaws.com','states.amazonaws.com'}-services
if __import__('os').environ.get('TRIGGER','both') in ('both','s3-event'): missing.add('events.amazonaws.com') if 'events.amazonaws.com' not in services else None
if missing: raise SystemExit('LabRole trust policy missing services: '+', '.join(sorted(missing))+'; cannot safely deploy without suitable role')
PY
if [[ "$AWS_REGION" == us-east-1 ]]; then aws s3api head-bucket --bucket "$S3_BUCKET" 2>/dev/null || aws s3api create-bucket --bucket "$S3_BUCKET" --region "$AWS_REGION"; else aws s3api head-bucket --bucket "$S3_BUCKET" 2>/dev/null || aws s3api create-bucket --bucket "$S3_BUCKET" --region "$AWS_REGION" --create-bucket-configuration LocationConstraint="$AWS_REGION"; fi
echo "SKIP S3 prefix creation (S3 prefixes are created automatically)"
# Content-hash based upload: unchanged local assets do not create new S3 versions.
upload_if_changed() {
  local local_file="$1" key="$2" local_hash remote_hash
  local_hash=$(python3 - "$local_file" <<'PYHASH'
import hashlib,sys
h=hashlib.sha256()
with open(sys.argv[1],'rb') as f:
    for b in iter(lambda:f.read(1024*1024),b''): h.update(b)
print(h.hexdigest())
PYHASH
)
  remote_hash=$(aws s3api head-object --bucket "$S3_BUCKET" --key "$key" --query 'Metadata.sha256' --output text 2>/dev/null || true)
  if [[ "$remote_hash" == "$local_hash" ]]; then
    echo "SKIP unchanged S3: $key"
  else
    aws s3api put-object --bucket "$S3_BUCKET" --key "$key" --body "$local_file" --metadata "sha256=$local_hash" >/dev/null
    echo "UPDATED S3: $key"
  fi
}

upload_if_changed metadata/bmr_stations.csv metadata/bmr_stations.csv
# station_coordinates.csv is generated by fetch_weather at runtime.
# Do not require or overwrite it during deployment.
echo "SKIP metadata/station_coordinates.csv (managed by fetch_weather)"
if [[ ! -f aws/lambdas/quarantine_batch/app.py ]]; then echo 'ERROR: state machine requires aws/lambdas/quarantine_batch/app.py (not in uploaded ZIP)' >&2; exit 1; fi
aws glue get-database --name "$GLUE_DATABASE" >/dev/null 2>&1 || aws glue create-database --database-input "{\"Name\":\"$GLUE_DATABASE\"}" >/dev/null
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
TMP_STAGING_TABLE_JSON="$TMP/staging-table.json"

# Verify_batch uses this non-Iceberg Parquet schema template to validate staging.
# Keep it distinct from the Iceberg publishing table.
STAGING_SCHEMA_TABLE=${STAGING_SCHEMA_TABLE:-pm25_weather}
if aws glue get-table --database-name "$GLUE_DATABASE" --name "$STAGING_SCHEMA_TABLE" >/dev/null 2>&1; then
  echo "SKIP existing Glue staging schema table: $GLUE_DATABASE.$STAGING_SCHEMA_TABLE"
else
  echo "Creating Glue staging schema table: $GLUE_DATABASE.$STAGING_SCHEMA_TABLE"
  python3 - "$S3_BUCKET" "$STAGING_SCHEMA_TABLE" > "$TMP_STAGING_TABLE_JSON" <<'PYSTAGING'
import json, sys
bucket, name = sys.argv[1:]
columns = [
    ('station_id', 'string'), ('date', 'date'), ('pm25', 'double'),
    ('temperature_2m_mean', 'double'), ('weather_code', 'int'),
    ('wind_speed_10m_max', 'double'), ('wind_direction_10m_dominant', 'double'),
    ('precipitation_sum', 'double'), ('precipitation_hours', 'double'),
    ('relative_humidity_2m_mean', 'double'), ('weather_description', 'string'),
    ('lat', 'double'), ('lon', 'double'),
]
serde = 'org.apache.hadoop.hive.ql.io.parquet.serde.ParquetHiveSerDe'
table = {
    'Name': name,
    'TableType': 'EXTERNAL_TABLE',
    'Parameters': {'EXTERNAL': 'TRUE', 'classification': 'parquet'},
    'PartitionKeys': [{'Name': 'year', 'Type': 'string'}, {'Name': 'month', 'Type': 'string'}],
    'StorageDescriptor': {
        'Columns': [{'Name': n, 'Type': t} for n, t in columns],
        'Location': f's3://{bucket}/curated/pm25_weather/',
        'InputFormat': 'org.apache.hadoop.hive.ql.io.parquet.MapredParquetInputFormat',
        'OutputFormat': 'org.apache.hadoop.hive.ql.io.parquet.MapredParquetOutputFormat',
        'SerdeInfo': {'SerializationLibrary': serde, 'Parameters': {'serialization.format': '1'}},
        'Compressed': False,
        'StoredAsSubDirectories': False,
    },
}
print(json.dumps(table))
PYSTAGING
  aws glue create-table --database-name "$GLUE_DATABASE" --table-input "file://$TMP_STAGING_TABLE_JSON" >/dev/null
  rm -f "$TMP_STAGING_TABLE_JSON"
  echo "CREATED Glue staging schema table: $GLUE_DATABASE.$STAGING_SCHEMA_TABLE"
fi
for fn in check_batch validate_batch fetch_weather validate_weather transform_batch verify_batch finalize_iceberg analysis_batch quarantine_batch; do
  src="aws/lambdas/$fn"; [[ -f "$src/app.py" ]] || { echo "Missing $src/app.py" >&2; exit 1; }
  # Stable ZIP bytes for identical source: Lambda CodeSha256 comparison is reliable.
  python3 - "$src" "$TMP/$fn.zip" <<'PYZIP'
from pathlib import Path
import sys,zipfile
src=Path(sys.argv[1]); dest=Path(sys.argv[2])
with zipfile.ZipFile(dest,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
    for f in sorted(src.rglob('*')):
        if not f.is_file() or any(x in ('__pycache__','.git','.pytest_cache') for x in f.parts) or f.suffix=='.pyc' or f.name=='RECORD' and '.dist-info' in str(f): continue
        info=zipfile.ZipInfo(f.relative_to(src).as_posix(),date_time=(2020,1,1,0,0,0))
        info.compress_type=zipfile.ZIP_DEFLATED
        info.external_attr=0o644 << 16
        z.writestr(info,f.read_bytes(),compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
PYZIP
  local_sha=$(python3 - "$TMP/$fn.zip" <<'PYSH'
import hashlib,base64,sys
print(base64.b64encode(hashlib.sha256(open(sys.argv[1],'rb').read()).digest()).decode())
PYSH
)
  timeout=60; [[ "$fn" == transform_batch || "$fn" == analysis_batch ]] && timeout=120
  envjson=$(python3 - "$S3_BUCKET" "$GLUE_DATABASE" "$ICEBERG_TABLE" <<'PY'
import json,sys
b,d,t=sys.argv[1:]
print(json.dumps({'Variables':{'DATA_BUCKET':b,'BUCKET_NAME':b,'GLUE_DATABASE':d,'GLUE_TABLE':t,'MASTER_KEY':'metadata/bmr_stations.csv','COORDINATES_KEY':'metadata/station_coordinates.csv','ATHENA_RESULTS_S3':f's3://{b}/athena-results/'}}))
PY
)
  if aws lambda get-function --function-name "$fn" >/dev/null 2>&1; then
    aws lambda get-function-configuration --function-name "$fn" > "$TMP/$fn-current.json"
    current_sha=$(aws lambda get-function --function-name "$fn" --query Configuration.CodeSha256 --output text)
    if [[ "$local_sha" != "$current_sha" ]]; then
      aws lambda update-function-code --function-name "$fn" --zip-file "fileb://$TMP/$fn.zip" >/dev/null
      aws lambda wait function-updated --function-name "$fn"
      echo "UPDATED Lambda code: $fn"
    else
      echo "SKIP unchanged Lambda code: $fn"
    fi
    if ! python3 - "$TMP/$fn-current.json" "$LAMBDA_RUNTIME" "$timeout" "$ROLE_ARN" "$envjson" <<'PYCONF'
import json,sys
c=json.load(open(sys.argv[1])); runtime,timeout,role=sys.argv[2:5]; env=json.loads(sys.argv[5])['Variables']
sys.exit(0 if c.get('Runtime')==runtime and c.get('Handler')=='app.handler' and c.get('Timeout')==int(timeout) and c.get('Role')==role and c.get('Environment',{}).get('Variables',{})==env else 1)
PYCONF
    then
      aws lambda update-function-configuration --function-name "$fn" --runtime "$LAMBDA_RUNTIME" --handler app.handler --timeout "$timeout" --role "$ROLE_ARN" --environment "$envjson" >/dev/null
      aws lambda wait function-updated --function-name "$fn"
      echo "UPDATED Lambda config: $fn"
    fi
  else
    aws lambda create-function --function-name "$fn" --runtime "$LAMBDA_RUNTIME" --handler app.handler --timeout "$timeout" --role "$ROLE_ARN" --zip-file "fileb://$TMP/$fn.zip" --environment "$envjson" >/dev/null
    echo "CREATED Lambda: $fn"
  fi
  aws lambda wait function-active-v2 --function-name "$fn"
  aws lambda wait function-updated --function-name "$fn"
  echo "OK Lambda: $fn (${timeout}s)"
done
GLUE_SCRIPT_KEY="scripts/$GLUE_JOB.py"
upload_if_changed "aws/glue/$GLUE_JOB/app.py" "$GLUE_SCRIPT_KEY"
python3 - "$ROLE_ARN" "$S3_BUCKET" "$GLUE_SCRIPT_KEY" "$GLUE_DATABASE" "$ICEBERG_TABLE" > "$TMP/glue.json" <<'PY'
import json,sys
role,b,key,db,table=sys.argv[1:]
print(json.dumps({'Role':role,'Command':{'Name':'glueetl','ScriptLocation':f's3://{b}/{key}','PythonVersion':'3'},'GlueVersion':'5.0','WorkerType':'G.1X','NumberOfWorkers':2,'DefaultArguments':{'--job-language':'python','--datalake-formats':'iceberg','--enable-glue-datacatalog':'true','--conf':f'spark.sql.extensions=org.apache.iceberg.spark.extensions.IcebergSparkSessionExtensions --conf spark.sql.catalog.glue_catalog=org.apache.iceberg.spark.SparkCatalog --conf spark.sql.catalog.glue_catalog.warehouse=s3://{b}/iceberg/ --conf spark.sql.catalog.glue_catalog.catalog-impl=org.apache.iceberg.aws.glue.GlueCatalog --conf spark.sql.catalog.glue_catalog.io-impl=org.apache.iceberg.aws.s3.S3FileIO','--DATABASE':db,'--TABLE':table}}))
PY
if aws glue get-job --job-name "$GLUE_JOB" >/dev/null 2>&1; then
  aws glue get-job --job-name "$GLUE_JOB" > "$TMP/glue-current.json"
  if python3 - "$TMP/glue-current.json" "$TMP/glue.json" <<'PYGLUE'
import json,sys
current=json.load(open(sys.argv[1]))['Job']; desired=json.load(open(sys.argv[2]))
fields=('Role','Command','GlueVersion','WorkerType','NumberOfWorkers','DefaultArguments')
sys.exit(0 if all(current.get(k)==desired.get(k) for k in fields) else 1)
PYGLUE
  then echo "SKIP unchanged Glue Job: $GLUE_JOB"
  else aws glue update-job --job-name "$GLUE_JOB" --job-update "file://$TMP/glue.json" >/dev/null; echo "UPDATED Glue Job: $GLUE_JOB"; fi
else aws glue create-job --name "$GLUE_JOB" --cli-input-json "file://$TMP/glue.json" >/dev/null; echo "CREATED Glue Job: $GLUE_JOB"; fi
if ! aws glue get-table --database-name "$GLUE_DATABASE" --name "$ICEBERG_TABLE" >/dev/null 2>&1; then
  python3 - "$S3_BUCKET" "$GLUE_DATABASE" "$ICEBERG_TABLE" > "$TMP/create.sql" <<'PY'
import sys
b,d,t=sys.argv[1:]
s=open('sql/create_iceberg_table.sql').read().replace('pm25_weather.pm25_weather_iceberg',f'{d}.{t}').replace('s3://pm25-weather/',f's3://{b}/')
print(s)
PY
  QID=$(aws athena start-query-execution --query-string "$(cat "$TMP/create.sql")" --result-configuration "OutputLocation=s3://$S3_BUCKET/athena-results/" --query QueryExecutionId --output text)
  while :; do state=$(aws athena get-query-execution --query-execution-id "$QID" --query QueryExecution.Status.State --output text); [[ "$state" == SUCCEEDED ]] && break; [[ "$state" == FAILED || "$state" == CANCELLED ]] && { aws athena get-query-execution --query-execution-id "$QID" --query QueryExecution.Status.StateChangeReason --output text >&2; exit 1; }; sleep 3; done
fi
python3 - "$AWS_REGION" "$ACCOUNT" "$GLUE_JOB" "$GLUE_DATABASE" "$ICEBERG_TABLE" > "$TMP/state_machine.json" <<'PY'
import json,sys
r,a,job,db,t=sys.argv[1:]
s=json.load(open('aws/step_function/state_machine.json'))
for state in s['States'].values():
    args=state.get('Arguments',{})
    fn=args.get('FunctionName')
    if isinstance(fn,str) and ':function:' in fn:
        name=fn.split(':function:',1)[1].split(':')[0]
        args['FunctionName']=f'arn:aws:lambda:{r}:{a}:function:{name}:$LATEST'
    if args.get('JobName'): args['JobName']=job
    if isinstance(args.get('Arguments'),dict):
        p=args['Arguments']
        if '--DATABASE' in p: p['--DATABASE']=db
        if '--TABLE' in p: p['--TABLE']=t
print(json.dumps(s))
PY
STATE_ARN="arn:aws:states:$AWS_REGION:$ACCOUNT:stateMachine:$STATE_MACHINE_NAME"
if aws stepfunctions describe-state-machine --state-machine-arn "$STATE_ARN" >/dev/null 2>&1; then
  aws stepfunctions describe-state-machine --state-machine-arn "$STATE_ARN" > "$TMP/state-current.json"
  if python3 - "$TMP/state-current.json" "$TMP/state_machine.json" "$ROLE_ARN" <<'PYSTATE'
import json,sys
c=json.load(open(sys.argv[1])); d=json.load(open(sys.argv[2])); role=sys.argv[3]
sys.exit(0 if json.loads(c['definition'])==d and c['roleArn']==role else 1)
PYSTATE
  then echo "SKIP unchanged Step Functions: $STATE_MACHINE_NAME"
  else aws stepfunctions update-state-machine --state-machine-arn "$STATE_ARN" --definition "$(cat "$TMP/state_machine.json")" --role-arn "$ROLE_ARN" >/dev/null; echo "UPDATED Step Functions: $STATE_MACHINE_NAME"; fi
else aws stepfunctions create-state-machine --name "$STATE_MACHINE_NAME" --definition "$(cat "$TMP/state_machine.json")" --role-arn "$ROLE_ARN" --type STANDARD >/dev/null; echo "CREATED Step Functions: $STATE_MACHINE_NAME"; fi
if [[ "$TRIGGER" == both || "$TRIGGER" == s3-event ]]; then
  # Read existing notifications once; AWS CLI may produce empty stdout for an empty config.
  # With set -e, an AWS CLI failure stops deployment rather than being treated as empty JSON.
  aws s3api get-bucket-notification-configuration \
    --bucket "$S3_BUCKET" --output json > "$TMP/notification.json"

  if python3 - "$TMP/notification.json" <<'PYNOTIFY'
import json, sys
from pathlib import Path

p = Path(sys.argv[1])
content = p.read_text(encoding='utf-8').strip()
try:
    obj = json.loads(content) if content else {}
except json.JSONDecodeError as exc:
    raise SystemExit(f'ERROR: Invalid S3 notification JSON: {exc}')
if not isinstance(obj, dict):
    raise SystemExit('ERROR: S3 notification configuration must be a JSON object')
if 'EventBridgeConfiguration' in obj:
    sys.exit(0)  # Already enabled; no update necessary.
obj['EventBridgeConfiguration'] = {}
p.write_text(json.dumps(obj), encoding='utf-8')
sys.exit(1)  # Must enable EventBridge.
PYNOTIFY
  then
    echo "SKIP S3 EventBridge notification: already enabled"
  else
    aws s3api put-bucket-notification-configuration \
      --bucket "$S3_BUCKET" \
      --notification-configuration "file://$TMP/notification.json"
    echo "ENABLED S3 EventBridge notification: $S3_BUCKET"
  fi
  RULE="pm25-weather-incoming"
  aws events put-rule --name "$RULE" --event-pattern "$(python3 - "$S3_BUCKET" <<'PY'
import json,sys
print(json.dumps({'source':['aws.s3'],'detail-type':['Object Created'],'detail':{'bucket':{'name':[sys.argv[1]]},'object':{'key':[{'prefix':'incoming/pm25/'}]}}}))
PY
)" --state ENABLED >/dev/null
  # EventBridge input transformer maps the S3 event to the Step Functions input schema.
  python3 - "$STATE_ARN" > "$TMP/targets.json" <<'PY'
import json,sys
print(json.dumps([{'Id':'pm25-pipeline','Arn':sys.argv[1],'RoleArn':None,'InputTransformer':{'InputPathsMap':{'bucket':'$.detail.bucket.name','key':'$.detail.object.key'},'InputTemplate':'{"bucket": <bucket>, "source_key": <key>}'}}]))
PY
  # Replace null RoleArn with existing role; Events must be trusted by that role.
  python3 - "$TMP/targets.json" "$ROLE_ARN" <<'PY'
import json,sys
p=sys.argv[1]; x=json.load(open(p)); x[0]['RoleArn']=sys.argv[2]; json.dump(x,open(p,'w'))
PY
  aws events put-targets --rule "$RULE" --targets "file://$TMP/targets.json" > "$TMP/put-targets.json"
  python3 - "$TMP/put-targets.json" <<'PYTARGET'
import json,sys
r=json.load(open(sys.argv[1])); assert r.get('FailedEntryCount',0)==0, r
PYTARGET
fi
printf '\n======================================================\n'
printf ' SUCCESS: All PM2.5 pipeline resources deployed!\n'
printf ' Bucket: s3://%s\n Database/Table: %s.%s\n Glue Job: %s\n Step Functions: %s\n Trigger: %s\n' "$S3_BUCKET" "$GLUE_DATABASE" "$ICEBERG_TABLE" "$GLUE_JOB" "$STATE_ARN" "$TRIGGER"
printf '======================================================\n'